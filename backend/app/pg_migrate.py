"""PostgreSQL / Supabase schema and data migration.

    python -m app.pg_migrate schema-sql                 # write supabase/migrations/*.sql from the SQLAlchemy models
    python -m app.pg_migrate copy --target postgresql://...  [--source sqlite:///data/pyroscope.db] [--dry-run]

`schema-sql` renders CREATE TABLE / INDEX statements with the PostgreSQL dialect (no SQLite syntax), then enables
Row Level Security on every table with NO policies and revokes table access from the Supabase `anon` and
`authenticated` roles: the browser never talks to PostgreSQL; FastAPI is the single authentication layer and
connects with a server-side role. A second file creates the private Storage buckets.

`copy` migrates application records (users, roles, organisations, contacts, alerts and history, thresholds,
dataset registry, jobs, model/scientific metadata, fire events ...) table by table in foreign-key order, in batches,
then resets PostgreSQL sequences and reconciles row counts. The source SQLite file is opened read-only and never
modified or deleted. Large analytical data (Parquet, rasters) stays in object storage, not PostgreSQL.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from sqlalchemy import create_engine, func, inspect, select, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from . import models as M
from .config import DATA, ROOT
from .storage import BUCKETS

MIGRATIONS = ROOT / "supabase" / "migrations"
SCHEMA_FILE = MIGRATIONS / "20261115000000_pyroscope_schema.sql"
BUCKETS_FILE = MIGRATIONS / "20261115000100_pyroscope_storage_buckets.sql"


def schema_sql() -> str:
    d = postgresql.dialect()
    out = ["-- PyroScope schema for PostgreSQL / Supabase. GENERATED by `python -m app.pg_migrate schema-sql`; do not edit by hand.",
           "-- Row Level Security is enabled with no policies: only the backend's server-side role (which bypasses RLS) reads or",
           "-- writes these tables. The Supabase anon / authenticated roles get no table privileges.", ""]
    for t in M.Base.metadata.sorted_tables:
        out.append(str(CreateTable(t, if_not_exists=True).compile(dialect=d)).strip() + ";")
        for i in sorted(t.indexes, key=lambda x: x.name or ""):
            out.append(str(CreateIndex(i, if_not_exists=True).compile(dialect=d)).strip() + ";")
        out.append("")
    out.append("CREATE TABLE IF NOT EXISTS schema_migrations (id SERIAL PRIMARY KEY, applied_at VARCHAR(40), summary TEXT);")
    out.append("")
    out.append("DO $$\nDECLARE r record;\nBEGIN\n  FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP\n"
               "    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.tablename);\n"
               "    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN\n"
               "      EXECUTE format('REVOKE ALL ON public.%I FROM anon', r.tablename);\n    END IF;\n"
               "    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN\n"
               "      EXECUTE format('REVOKE ALL ON public.%I FROM authenticated', r.tablename);\n    END IF;\n"
               "  END LOOP;\nEND $$;")
    return "\n".join(out) + "\n"


def buckets_sql() -> str:
    rows = ",\n".join(f"  ('{b}', '{b}', false)" for b in BUCKETS)
    return ("-- Private Supabase Storage buckets for PyroScope. GENERATED by `python -m app.pg_migrate schema-sql`.\n"
            "-- No storage.objects policies are created: only the service role (backend) can read/write; browsers get signed URLs.\n"
            f"INSERT INTO storage.buckets (id, name, public) VALUES\n{rows}\nON CONFLICT (id) DO NOTHING;\n")


def write_sql() -> list[str]:
    MIGRATIONS.mkdir(parents=True, exist_ok=True)
    SCHEMA_FILE.write_text(schema_sql(), encoding="utf-8", newline="\n")
    BUCKETS_FILE.write_text(buckets_sql(), encoding="utf-8", newline="\n")
    return [str(SCHEMA_FILE.relative_to(ROOT)), str(BUCKETS_FILE.relative_to(ROOT))]


def copy(source: str, target: str, dry_run: bool = False, batch: int = 2000, log=print) -> dict:
    """Copy every model table from source to target. Target tables are created if missing; existing target rows
    with the same primary key are left untouched (re-runnable). Returns per-table reconciliation."""
    if source.startswith("sqlite:///"):
        p = Path(source.replace("sqlite:///", "", 1))
        if not p.exists():
            raise FileNotFoundError(p)
        src = create_engine(f"sqlite:///file:{p.as_posix()}?mode=ro&uri=true")
    else:
        src = create_engine(M.normalise_url(source))
    dst = M.make_engine(target)
    have_src = set(inspect(src).get_table_names())
    if not dry_run:
        M.Base.metadata.create_all(dst)
    report = {}
    for t in M.Base.metadata.sorted_tables:
        if t.name not in have_src:
            report[t.name] = {"source": 0, "status": "absent in source"}
            continue
        src_cols = {c["name"] for c in inspect(src).get_columns(t.name)}
        cols = [c for c in t.columns if c.name in src_cols]
        with src.connect() as sc:
            n_src = sc.execute(select(func.count()).select_from(t)).scalar()
        if dry_run:
            report[t.name] = {"source": n_src, "status": "dry-run"}
            continue
        pk = [c.name for c in t.primary_key.columns]
        copied = 0
        with src.connect() as sc, dst.begin() as dc:
            existing = {tuple(r) for r in dc.execute(select(*[t.c[k] for k in pk]))} if pk else set()
            rows = sc.execute(select(*cols)).mappings()
            buf = []
            for r in rows:
                if pk and tuple(r[k] for k in pk) in existing:
                    continue
                buf.append(dict(r))
                if len(buf) >= batch:
                    dc.execute(t.insert(), buf)
                    copied += len(buf)
                    buf = []
            if buf:
                dc.execute(t.insert(), buf)
                copied += len(buf)
            if dst.dialect.name == "postgresql" and pk == ["id"]:
                dc.execute(text(f"SELECT setval(pg_get_serial_sequence('{t.name}', 'id'), COALESCE((SELECT MAX(id) FROM {t.name}), 1))"))
        with dst.connect() as dc2:
            n_dst = dc2.execute(select(func.count()).select_from(t)).scalar()
        report[t.name] = {"source": n_src, "copied": copied, "target": n_dst, "status": "OK" if n_dst >= n_src else "MISMATCH"}
        log(f"[pg_migrate] {t.name}: {report[t.name]}")
    return {"source": source.split("@")[-1], "target": target.split("@")[-1], "tables": report,
            "reconciled": all(v.get("status") in ("OK", "absent in source", "dry-run") for v in report.values()),
            "source_untouched": True}


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m app.pg_migrate")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("schema-sql")
    c = sub.add_parser("copy")
    c.add_argument("--source", default=f"sqlite:///{(DATA / 'pyroscope.db').as_posix()}")
    c.add_argument("--target", required=True)
    c.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    if a.cmd == "schema-sql":
        print("\n".join(write_sql()))
        return 0
    res = copy(a.source, a.target, a.dry_run)
    print(json.dumps(res, indent=1, default=str))
    return 0 if res["reconciled"] else 1


if __name__ == "__main__":
    sys.exit(main())
